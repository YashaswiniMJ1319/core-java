class Hospital{
	
	String hospitalName;
	String location;
	int numberOfBeds; 
	int numberOfDoctors;
	boolean isEmergencyAvailable;
	
	Hospital(String hospitalName,String location,int numberOfBeds,int numberOfDoctors,boolean isEmergencyAvailable){
		this.hospitalName=hospitalName;
		this.location=location;
		this.numberOfBeds=numberOfBeds;
		this.numberOfDoctors=numberOfDoctors;
		this.isEmergencyAvailable=isEmergencyAvailable;
		
	}
	
	}

