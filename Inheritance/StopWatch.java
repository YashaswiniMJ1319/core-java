class StopWatch {

    void start() { 
	System.out.println("starting stopwatch"); 
	}
	
    void stop() { 
	System.out.println("stopping stopwatch"); 
	}
	
    void reset() { 
	System.out.println("resetting stopwatch"); 
	}
    void pause() { 
	System.out.println("pausing stopwatch"); 
	}
	
    void showTime() { 
	System.out.println("showing time"); 
	}
}

