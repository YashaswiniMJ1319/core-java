class Tape {

    void playTape() {
        System.out.println("playing tape");
    }

    void stopTape() {
        System.out.println("stopping tape");
    }

    void rewindTape() {
        System.out.println("rewinding tape");
    }

    void forwardTape() {
        System.out.println("forwarding tape");
    }

    void ejectTape() {
        System.out.println("ejecting tape");
    }
}