class Temple{
	
	String templeName;
	String location;
	String deity;
	int yearBuilt;
	boolean isOpen;
	
	Temple(String templeName,String location,String deity,int yearBuilt,boolean isOpen){
		
		this.templeName=templeName;
		this.location=location;
		this.deity=deity;
		this.yearBuilt=yearBuilt;
		this.isOpen=isOpen;
	}

}