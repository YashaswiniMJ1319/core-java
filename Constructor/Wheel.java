class Wheel {

    String brand;
    String type;
    int size;
    String material;
    double price;
    String color;
    double weight;
    boolean tubeless;
    String vehicleType;
    String durability;

    
    Wheel(String brand, String type, int size, String material, double price,
          String color, double weight, boolean tubeless, String vehicleType, String durability) {

        this.brand = brand;
        this.type = type;
        this.size = size;
        this.material = material;
        this.price = price;
        this.color = color;
        this.weight = weight;
        this.tubeless = tubeless;
        this.vehicleType = vehicleType;
        this.durability = durability;
    }
}


    
