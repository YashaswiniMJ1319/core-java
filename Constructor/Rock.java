class Rock {

    String name;
    String type;
    String color;
    double weight;
    double price;
    String texture;
    String hardness;
    String origin;
    String usage;
    String durability;

    Rock(String name, String type, String color, double weight, double price,
         String texture, String hardness, String origin, String usage, String durability) {

        this.name = name;
        this.type = type;
        this.color = color;
        this.weight = weight;
        this.price = price;
        this.texture = texture;
        this.hardness = hardness;
        this.origin = origin;
        this.usage = usage;
        this.durability = durability;
    }
}