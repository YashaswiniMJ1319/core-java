class DumbBells {

    String brand;
    double weight;
    String material;
    double price;
    String color;
    String type;
    boolean adjustable;
    String gripType;
    String shape;
    String durability;

    DumbBells(String brand, double weight, String material, double price,
              String color, String type, boolean adjustable,
              String gripType, String shape, String durability) {

        this.brand = brand;
        this.weight = weight;
        this.material = material;
        this.price = price;
        this.color = color;
        this.type = type;
        this.adjustable = adjustable;
        this.gripType = gripType;
        this.shape = shape;
        this.durability = durability;
    }
}