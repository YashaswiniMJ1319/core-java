class Bell {

    String brand;
    String type;
    String material;
    double weight;
    double price;
    String color;
    double size;
    String soundLevel;
    String usage;
    String durability;

    Bell(String brand, String type, String material, double weight,
         double price, String color, double size, String soundLevel,
         String usage, String durability) {

        this.brand = brand;
        this.type = type;
        this.material = material;
        this.weight = weight;
        this.price = price;
        this.color = color;
        this.size = size;
        this.soundLevel = soundLevel;
        this.usage = usage;
        this.durability = durability;
    }
}