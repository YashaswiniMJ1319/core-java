class ThreadMill {

    String brand;
    String model;
    double price;
    double weight;
    String type;
    double speed;
    boolean automatic;
    String usage;
    String color;
    String warranty;

    ThreadMill(String brand, String model, double price, double weight,
               String type, double speed, boolean automatic,
               String usage, String color, String warranty) {

        this.brand = brand;
        this.model = model;
        this.price = price;
        this.weight = weight;
        this.type = type;
        this.speed = speed;
        this.automatic = automatic;
        this.usage = usage;
        this.color = color;
        this.warranty = warranty;
    }
}