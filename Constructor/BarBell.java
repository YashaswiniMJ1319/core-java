class BarBell {

    String brand;
    double weight;
    String material;
    double price;
    String color;
    String type;
    boolean bearing;
    double length;
    String grip;
    String durability;

    BarBell(String brand, double weight, String material, double price,
            String color, String type, boolean bearing, double length,
            String grip, String durability) {

        this.brand = brand;
        this.weight = weight;
        this.material = material;
        this.price = price;
        this.color = color;
        this.type = type;
        this.bearing = bearing;
        this.length = length;
        this.grip = grip;
        this.durability = durability;
    }
}