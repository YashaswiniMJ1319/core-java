class AsianPaint {

    String productName;
    String color;
    String finish;
    double price;
    double quantity;
    String type;
    boolean waterproof;
    String surface;
    String durability;
    String brand;

    AsianPaint(String productName, String color, String finish,
               double price, double quantity, String type,
               boolean waterproof, String surface,
               String durability, String brand) {

        this.productName = productName;
        this.color = color;
        this.finish = finish;
        this.price = price;
        this.quantity = quantity;
        this.type = type;
        this.waterproof = waterproof;
        this.surface = surface;
        this.durability = durability;
        this.brand = brand;
    }
}